/*!MD
# sos_preset
Frequencies and ACF of a predefined sum-of-sinusoids generator

- Returns a precomputed frequency table for [[sos_val]] together with the autocorrelation function (ACF)
  it was fitted to
- Presets: `Exp128`, `Exp256`, `Exp512`, `Exp1024`, `Gauss128`, `Gauss256`, `Gauss512`, `Gauss1024`,
  `Comb128`, `Comb256`, `Comb512`, `Comb1024`. The number is the number of sinusoids, `n_coeff`. The name is
  matched exactly, including upper and lower case
- ACF types, with the distance `D` and the decorrelation distance `d`: `Exp`: `R = exp( -D/d )`;
  `Gauss`: `R = exp( -(D/d)^2 )`; `Comb`: `Gauss` for `D <= d`, `Exp` beyond. All three have `R(d) = exp(-1)`
- The ACF is returned as a table with 200 samples from 0 to `4.975·d` in steps of `0.025·d`
- The tables are stored for `d = 10 m`. For another decorrelation distance the distances are multiplied by
  `d/10` and the frequencies by `10/d`
- All tables are 3-dimensional and can be used with positions of 1, 2 or 3 columns
- The outputs cannot be the same object or share memory with each other; such a call throws before anything
  is written
- How the tables were made: [[sos_generate]] with the 200-sample ACF for 10 m, `n_dim = 3`,
  `uniform_smp = true`, `n_dir = 300`, `random_init = true`, `freq_min = 0.005`, `freq_max = 15 / 49.75`,
  and the seeds 39, 3, 2, 5 (Exp), 13, 32, 6, 21 (Gauss), 13, 25, 37, 47 (Comb) for 128, 256, 512 and 1024
  sinusoids. Sinusoid `n` points in direction `n` of the spiral lattice described in [[sos_calc_mse]]
- The lower frequency limit means that no sinusoid has a wavelength above 20 decorrelation distances. The
  ACF of the tables therefore stays near zero beyond the fitted range (magnitude below 0.015 at 10, 20, 50
  and 100 decorrelation distances), and the mean of the generator over a large area is not offset by
  sinusoids of nearly zero frequency

## Declaration:
```
void quadriga_lib::sos_preset(
    const std::string &name,
    arma::Mat<dtype> &freq,
    arma::Col<dtype> *acf = nullptr,
    arma::Col<dtype> *dist = nullptr,
    dtype dist_decorr = 10.0);
```

## Inputs:
- **`name`** — Name of the preset, e.g. `"Comb256"`
- **`dist_decorr`** *(optional)* — Decorrelation distance in [m]; must be > 0

## Outputs:
- **`freq`** — Frequencies in [1/m]; `[n_coeff, 3]`
- **`acf`** *(optional)* — Target ACF; `[200]`
- **`dist`** *(optional)* — Sample points of the ACF in [m]; `[200]`

## See also:
- [[sos_init_phases]] (random phases for the generator)
- [[sos_val]] (evaluation)
- [[sos_generate]] (frequencies for other ACFs)
MD!*/

template <typename dtype>
void quadriga_lib::sos_preset(const std::string &name,
                              arma::Mat<dtype> &freq,
                              arma::Col<dtype> *acf,
                              arma::Col<dtype> *dist,
                              dtype dist_decorr)
{
    // ACF type: 0 = Exp, 1 = Gauss, 2 = Comb
    int type = -1;
    arma::uword n_coeff = 0;
    if (!qd_sos_preset_lookup(name, type, n_coeff))
        throw std::invalid_argument("Input 'name' is not a known preset.");
    if (!(dist_decorr > (dtype)0.0) || !std::isfinite((double)dist_decorr))
        throw std::invalid_argument("Input 'dist_decorr' must be > 0.");

    // The outputs are written one after the other, so none of them can be another one or share memory with it
    const arma::Mat<dtype> *outputs[3] = {&freq, acf, dist};
    const char *output_names[3] = {"freq", "acf", "dist"};
    for (int i = 1; i < 3; ++i)
        for (int j = 0; j < i; ++j)
            if (outputs[i] != nullptr && outputs[j] != nullptr &&
                (outputs[i] == outputs[j] || qd_sos_share_memory(*outputs[i], *outputs[j])))
                throw std::invalid_argument(std::string("Output '") + output_names[i] + "' cannot share memory with '" +
                                            output_names[j] + "'.");

    const double *tables[3][4] = {
        {qd_sos_table_Exp128, qd_sos_table_Exp256, qd_sos_table_Exp512, qd_sos_table_Exp1024},
        {qd_sos_table_Gauss128, qd_sos_table_Gauss256, qd_sos_table_Gauss512, qd_sos_table_Gauss1024},
        {qd_sos_table_Comb128, qd_sos_table_Comb256, qd_sos_table_Comb512, qd_sos_table_Comb1024}};
    const double *table = tables[type][n_coeff == 128 ? 0 : (n_coeff == 256 ? 1 : (n_coeff == 512 ? 2 : 3))];

    // The tables are stored for 10 m
    const double scale = (double)dist_decorr / 10.0;

    std::vector<double> ux(n_coeff), uy(n_coeff), uz(n_coeff);
    qd_sos_directions(n_coeff, 3, ux.data(), uy.data(), uz.data());

    if (freq.n_rows != n_coeff || freq.n_cols != 3)
        freq.set_size(n_coeff, 3);
    for (arma::uword n = 0; n < n_coeff; ++n)
    {
        double f = table[n] / scale;
        freq.at(n, 0) = (dtype)(f * ux[n]), freq.at(n, 1) = (dtype)(f * uy[n]), freq.at(n, 2) = (dtype)(f * uz[n]);
    }

    if (acf != nullptr)
    {
        if (acf->n_elem != 200)
            acf->set_size(200);
        for (arma::uword i = 0; i < 200; ++i)
        {
            double x = 0.25 * (double)i / 10.0; // Distance in decorrelation distances
            double gauss = std::exp(-x * x), expo = std::exp(-x);
            acf->at(i) = (dtype)(type == 0 ? expo : (type == 1 ? gauss : (i <= 40 ? gauss : expo)));
        }
    }

    if (dist != nullptr)
    {
        if (dist->n_elem != 200)
            dist->set_size(200);
        for (arma::uword i = 0; i < 200; ++i)
            dist->at(i) = (dtype)(0.25 * (double)i * scale);
    }
}

